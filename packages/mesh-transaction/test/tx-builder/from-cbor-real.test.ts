const params: Protocol = { ...DEFAULT_PROTOCOL_PARAMETERS };

/** The out refs a transaction names, and the network its outputs are of */
const namedBy = (hex: string) => {
  const body = Serialization.Transaction.fromCbor(hex as never).body();
  const refs = [
    body.inputs(),
    body.collateral(),
    body.referenceInputs(),
  ].flatMap((set) =>
    (set?.values() ?? []).map((input) => ({
      txHash: input.transactionId().toString(),
      outputIndex: Number(input.index()),
    })),
  );
  const networks = body
    .outputs()
    .map((output) => output.address().getNetworkId());
  return { refs, network: networks.includes(1) ? 1 : 0 };
};

describe("TxBuilder.fromCbor › real transactions", () => {
  it.each(REAL.map((hex, i) => [i, hex] as const))(
    "reads transaction %i, made for it UTxOs of a key of its network",
    async (_, hex) => {
      await Crypto.ready();
      const { refs, network } = namedBy(hex);
      const address = Address.fromBytes(
        `${network === 1 ? "61" : "60"}${"00".repeat(28)}` as never,
      ).toBech32() as string;
      const knownUtxos: Utxo[] = refs.map((ref) => ({
        ...ref,
        address,
        value: { lovelace: 1_000_000_000_000n },
      }));
      const work = scanTransaction(hex)!;
      expect(work).toBeLessThan(MAX_TX_WORK / 1000);
      const made = await new TxBuilder({
        network: network === 1 ? "mainnet" : "preprod",
        params,
      }).fromCbor(hex, { knownUtxos });
      expect(made.txHash).toBe(blake(topItems(hex)[0]!, 32));
      expect(made.inputs).toHaveLength(
        refs.length -
          made.referenceInputs.length -
          (made.collateral?.inputs.length ?? 0),
      );
    },
  );
});
